def glyph_pixels(index, scale):  # type: (int, int) -> List[List[int]]
    cols = GLCD[index]
    w, h = 5 * scale, 8 * scale
    pix = [[0] * w for _ in range(h)]
    for x, col in enumerate(cols):
        for y in range(8):
            if (col >> y) & 1:
                for dy in range(scale):
                    for dx in range(scale):
                        pix[y * scale + dy][x * scale + dx] = 1
    return pix


def tight(pix):  # type: (List[List[int]]) -> Tuple[List[List[int]], int, int]
    if not pix:
        return [], 0, 0
    h, w = len(pix), len(pix[0])
    rows = [i for i, row in enumerate(pix) if any(row)]
    if not rows:
        return [], 0, 0
    cols = [i for i in range(w) if any(pix[r][i] for r in range(h))]
    y0, y1 = rows[0], rows[-1]
    x0, x1 = cols[0], cols[-1]
    return [row[x0 : x1 + 1] for row in pix[y0 : y1 + 1]], x0, y0


def pack_bits(pix):  # type: (List[List[int]]) -> bytes
    bits = []  # type: List[int]
    for row in pix:
        bits.extend(row)
    out = bytearray()
    acc = 0
    n = 0
    for b in bits:
        acc = (acc << 1) | b
        n += 1
        if n == 8:
            out.append(acc)
            acc = 0
            n = 0
    if n:
        out.append(acc << (8 - n))
    return bytes(out)


def emit(name: str, scale: int, path: Path) -> None:
    cell = 6 * scale
    line = 8 * scale
    bitmaps = bytearray()
    dsc = [
        "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},"
    ]
    for i in range(95):
        pix = glyph_pixels(i, scale)
        tight_pix, ox, oy = tight(pix)
        start = len(bitmaps)
        if tight_pix:
            bitmaps.extend(pack_bits(tight_pix))
            bw, bh = len(tight_pix[0]), len(tight_pix)
        else:
            bw = bh = 0
            ox = oy = 0
        baseline_from_top = 7 * scale
        ofs_y = baseline_from_top - (oy + bh) if bh else 0
        dsc.append(
            f"    {{.bitmap_index = {start}, .adv_w = {cell * 16}, "
            f".box_w = {bw}, .box_h = {bh}, .ofs_x = {ox}, .ofs_y = {ofs_y}}},"
        )

    hex_bytes = ", ".join(f"0x{b:02x}" for b in bitmaps)
    wrapped = []
    row = []  # type: List[str]
    for item in hex_bytes.split(", "):
        row.append(item)
        if len(row) == 16:
            wrapped.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        wrapped.append("    " + ", ".join(row) + ",")

    guard = name.upper()
    text = f"""/* 1-bit {cell}x{line} cell, Adafruit GLCD 5x7. Generated by scripts/gen_pixel_font.py */
#include "lvgl.h"

#ifndef {guard}
#define {guard} 1
#endif

#if {guard}

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{chr(10).join(wrapped)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{chr(10).join(dsc)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = 32, .range_length = 95, .glyph_id_start = 1,
        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY
    }}
}};

#if LVGL_VERSION_MAJOR == 8
static lv_font_fmt_txt_glyph_cache_t cache;
#endif

#if LVGL_VERSION_MAJOR >= 8
static const lv_font_fmt_txt_dsc_t font_dsc = {{
#else
static lv_font_fmt_txt_dsc_t font_dsc = {{
#endif
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 1,
    .kern_classes = 0,
    .bitmap_format = 0,
#if LVGL_VERSION_MAJOR == 8
    .cache = &cache
#endif
}};

#if LVGL_VERSION_MAJOR >= 8
const lv_font_t {name} = {{
#else
lv_font_t {name} = {{
#endif
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line},
    .base_line = {scale},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1,
    .underline_thickness = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};

#endif
"""
    path.write_text(text)


def main() -> None:
    root = Path(__file__).resolve().parents[1] / "src" / "fonts"
    emit("font_pixel_6x8", 1, root / "font_pixel_6x8.c")
    emit("font_pixel_18x24", 3, root / "font_pixel_18x24.c")
    print("wrote font_pixel_6x8.c and font_pixel_18x24.c")


if __name__ == "__main__":
    main()
