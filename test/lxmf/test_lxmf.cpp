// (Python's `msgpack`, via a scratchpad script) rather than hand-assembled,
// so a mistake shared between a hand-built fixture and the reader under test
// cannot pass unnoticed. The specification's payload order is
// [timestamp, content, title, fields] -- content before title -- and a decoder
// that has those two the wrong way round parses every message without
// complaint while labelling all of them wrongly, so it is asserted directly.

